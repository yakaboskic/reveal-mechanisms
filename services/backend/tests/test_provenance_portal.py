def ref(cls, name): return f'dapper:{cls}.{name:x<32}'


def bottom_line_document(artifact=ARTIFACT, *, extra_drs=False):
    """Shaped like the portal's get_provenance document (T2D Mixed): R (the published Dataset) has the DrsObject; it was
    generated by a load step that used ancestry-specific Datasets, generated from intake files generated from raw files."""
    R, load, meta = ref('Dataset', 'published'), ref('Activity', 'load'), ref('Activity', 'metal')
    eu, intake, scale = ref('Dataset', 'eu'), ref('Activity', 'intake'), ref('Activity', 'scale')
    processed, raw_a, raw_b, unreached = ref('C2M2File', 'processed'), ref('C2M2File', 'rawa'), ref('C2M2File', 'rawb'), ref('C2M2File', 'other')
    drs = ref('DrsObject', 'drs')
    provenance = {
        'activities': [{'id': node, 'name': node[14:20], 'activity_type': 'Stage', 'description': None} for node in (load, meta, intake, scale)],
        'c2m2_files': [{'id': processed, 'name': 'processed', 'filename': 'T2D'}, {'id': raw_a, 'name': 'Raw variants A', 'filename': 'T2D',
                        'local_id': 's3://dig-analysis-data/variants_raw/A/T2D/'}, {'id': raw_b, 'name': 'Raw variants B', 'filename': 'T2D'},
                       {'id': unreached, 'name': 'unrelated'}],
        'datasets': [{'id': R, 'name': 'Published open-data bottom-line result for T2D / Mixed', 'access_level': 'public', 'version': '1',
                      'resource_type': 'dataset', 'description': None},
                     {'id': eu, 'name': 'Bottom-line ancestry-specific result for T2D / EU', 'access_level': 'controlled'}],
        'drs_objects': [{'id': drs, 'drs_id': artifact, 'name': 'T2D.sumstats.tsv.gz', 'access_methods': ['s3']}],
        'has_drs_object_edges': [{'subject': R, 'predicate': 'dapper:hasDrsObject', 'object': drs}],
        'used_edges': [{'subject': load, 'predicate': 'prov:used', 'object': eu, 'edge_role': 'data_input'},
                       {'subject': meta, 'predicate': 'prov:used', 'object': processed, 'edge_role': 'data_input'},
                       {'subject': scale, 'predicate': 'prov:used', 'object': raw_a, 'edge_role': 'data_input'},
                       {'subject': meta, 'predicate': 'prov:used', 'object': raw_b, 'edge_role': 'data_input'}],
        'was_generated_by_edges': [{'subject': R, 'predicate': 'prov:wasGeneratedBy', 'object': load},
                                   {'subject': eu, 'predicate': 'prov:wasGeneratedBy', 'object': meta},
                                   {'subject': processed, 'predicate': 'prov:wasGeneratedBy', 'object': scale}]}
    if extra_drs:
        provenance['has_drs_object_edges'].append({'subject': eu, 'predicate': 'dapper:hasDrsObject', 'object': drs})
    return {'id': artifact, 'name': 'Published open-data bottom-line result for T2D / Mixed', 'ancestry_id': 'Mixed',
            'pipeline_type': 'bottom-line', 'trait_legacy_id': 'T2D', 'provenance': provenance}, (R, raw_a, raw_b, unreached)


def test_compaction_keeps_the_published_dataset_and_its_raw_inputs_only():
    document, (R, raw_a, raw_b, unreached) = bottom_line_document()
    graph = portal.compact(document, ARTIFACT, base=BASE, portal='u', document_sha256='d' * 64)
    href = BASE + '/artifact/' + ARTIFACT
    assert graph['dataset'] == {'id': R, 'name': 'Published open-data bottom-line result for T2D / Mixed', 'version': '1',
                                'access_level': 'public', 'href': href}
    assert [(node['id'], node['path_length']) for node in graph['raw_inputs']] == sorted([(raw_a, 6), (raw_b, 4)])
    assert all(node['href'] == href and 'local_id' not in node for node in graph['raw_inputs'])  # generated intermediates and unreached files are not inputs
    assert (graph['portal_url'], graph['document_sha256'], graph['artifact_id']) == ('u', 'd' * 64, ARTIFACT)
    lineage = portal.trait_lineage('KPN.TRAIT:0000398', portal.Outcome('ok', ARTIFACT, 'u', graph, 's' * 64))
    assert lineage['published_gwas_edges'] == [{'subject': 'KPN.TRAIT:0000398', 'predicate': 'reveal:publishedGwas', 'object': R,
        'artifact_id': ARTIFACT, 'provenance_source': {'kind': 'portal_bottom_line', 'portal_url': 'u', 'sha256': 's' * 64}}]
    assert {(edge['subject'], edge['object'], edge['path_length']) for edge in lineage['portal_transitive_input_edges']} == {(R, raw_a, 6), (R, raw_b, 4)}
    assert all('path_length' not in node for node in lineage['c2m2_files'])
    # Exactly one Dataset must carry the artifact's DrsObject.
    assert portal.compact(bottom_line_document(extra_drs=True)[0], ARTIFACT) is None
    assert portal.compact(document, 'another-artifact') is None
    assert portal.compact({'provenance': []}, ARTIFACT) is None


def run(coroutine):
    async def main():
        try: return await coroutine
        finally: await portal.aclose()
    return asyncio.run(main())


class Portal:
    """A MockTransport portal: responses queued per call (a callable may raise), every request recorded."""
    def __init__(self, *responses, delay=0):
        self.responses, self.requests, self.delay = list(responses), [], delay

    async def handle(self, request):
        self.requests.append(request)
        if self.delay: await asyncio.sleep(self.delay)
        response = self.responses.pop(0) if len(self.responses) > 1 else self.responses[0]
        return response(request) if callable(response) else response

    def client(self):
        return httpx.AsyncClient(transport=httpx.MockTransport(self.handle), follow_redirects=False)


@pytest.fixture
def mock(monkeypatch):
    portal._CACHE.clear()
    monkeypatch.setenv(portal.PORTAL_ENV, BASE + '/')
    monkeypatch.setattr(portal, 'RETRY_SECONDS', 0)
    def install(*responses, delay=0):
        server = Portal(*responses, delay=delay)
        monkeypatch.setattr(portal, '_new_client', server.client)
        return server
    yield install
    portal._CACHE.clear()


def ok(document=None):
    return httpx.Response(200, content=json.dumps(document or bottom_line_document()[0]).encode())


class Clock:
    def __init__(self): self.now = 1000.0
    def monotonic(self): return self.now
    def time(self): return self.now


def test_ok_is_fetched_once_parsed_in_memory_and_cached(mock):
    server = mock(ok())
    first = run(portal.bottom_line(ARTIFACT))
    assert first.status == 'ok' and first.graph['dataset']['href'] == BASE + '/artifact/' + ARTIFACT
    assert first.portal_url == BASE + '/get_provenance?id=' + ARTIFACT and len(first.sha256) == 64
    assert first.sha256 == portal.hashlib.sha256(portal.canonical(first.graph)).hexdigest()
    assert run(portal.bottom_line(ARTIFACT)) == first and len(server.requests) == 1
    request = server.requests[0]
    assert request.url.params['id'] == ARTIFACT and request.headers['accept'] == 'application/json'


def test_nan_maps_to_null_and_a_404_is_cached_only_for_five_minutes(mock, monkeypatch):
    document = json.dumps(bottom_line_document()[0]).replace('"version": "1"', '"version": NaN, "score": Infinity')
    mock(httpx.Response(200, content=document.encode()))
    outcome = run(portal.bottom_line(ARTIFACT))
    assert outcome.status == 'ok' and 'version' not in outcome.graph['dataset']
    clock = Clock(); monkeypatch.setattr(portal, 'time', clock)
    server = mock(httpx.Response(404))
    assert run(portal.bottom_line('missing')).status == 'not_found'
    clock.now += portal.NEGATIVE_SECONDS - 1
    assert run(portal.bottom_line('missing')).status == 'not_found' and len(server.requests) == 1
    clock.now += 2
    assert run(portal.bottom_line('missing')).status == 'not_found' and len(server.requests) == 2


def test_oversize_bodies_and_malformed_documents_are_invalid(mock):
    big = b'{"x": "' + b'a' * (portal.MAX_BYTES + 1) + b'"}'
    mock(httpx.Response(200, content=big))
    assert run(portal.bottom_line('declared')).reason == 'oversize'
    async def chunks():
        for start in range(0, len(big), 1 << 20): yield big[start:start + (1 << 20)]
    server = mock(lambda request: httpx.Response(200, content=chunks()))  # streamed: no declared length
    outcome = run(portal.bottom_line('chunked'))
    assert (outcome.status, outcome.reason) == ('invalid', 'oversize') and len(server.requests) == 1
    mock(httpx.Response(200, content=b'{not json'))
    assert run(portal.bottom_line('malformed')).reason == 'malformed_document'
    mock(ok({'provenance': {}}))
    assert run(portal.bottom_line('nodataset')).reason == 'no_single_artifact_dataset'


def test_transport_errors_5xx_and_429_are_retried_once_and_never_cached(mock):
    def timeout(request): raise httpx.ReadTimeout('slow', request=request)
    server = mock(timeout)
    outcome = run(portal.bottom_line(ARTIFACT))
    assert (outcome.status, outcome.reason, len(server.requests)) == ('unavailable', 'ReadTimeout', 2)
    server = mock(httpx.Response(503), ok())
    assert run(portal.bottom_line(ARTIFACT)).status == 'ok' and len(server.requests) == 2  # the earlier failure was not cached
    portal._CACHE.clear()
    server = mock(httpx.Response(429, headers={'Retry-After': '0'}), ok())
    assert run(portal.bottom_line(ARTIFACT)).status == 'ok' and len(server.requests) == 2
    portal._CACHE.clear()
    server = mock(httpx.Response(302, headers={'Location': 'https://elsewhere.test/'}))
    outcome = run(portal.bottom_line(ARTIFACT))
    assert (outcome.status, outcome.reason, len(server.requests)) == ('unavailable', 'http_302', 1)  # never followed or retried


def test_retry_after_is_capped_to_the_remaining_budget(mock, monkeypatch):
    monkeypatch.setattr(portal, 'FETCH_BUDGET_SECONDS', 1.5)
    slept = []
    real_sleep = asyncio.sleep
    async def sleep(seconds): slept.append(seconds); await real_sleep(0)
    monkeypatch.setattr(portal.asyncio, 'sleep', sleep)
    server = mock(httpx.Response(429, headers={'Retry-After': '3600'}), ok())
    outcome = run(portal.bottom_line(ARTIFACT))
    assert outcome.status == 'ok' and len(server.requests) == 2 and slept and slept[0] <= 0.5


def test_a_body_that_never_ends_stops_at_the_fetch_budget_and_frees_its_slot(mock, monkeypatch):
    monkeypatch.setattr(portal, 'FETCH_BUDGET_SECONDS', 0.5)
    async def drip():  # every read arrives within httpx's read timeout; the body never ends
        yield b'{"provenance": '
        await asyncio.sleep(3600)
        yield b'{}}'
    server = mock(lambda request: httpx.Response(200, content=drip()))
    async def fetch():
        loop = asyncio.get_running_loop(); started = loop.time()
        outcome = await portal.bottom_line(ARTIFACT, timeout=30)
        await asyncio.sleep(0)
        state = portal._state()
        return outcome, loop.time() - started, dict(state.inflight), state.slots._value
    outcome, elapsed, inflight, free = run(fetch())
    assert (outcome.status, outcome.reason, len(server.requests)) == ('unavailable', 'timeout', 1) and elapsed < 2
    assert inflight == {} and free == portal.CONCURRENCY  # the shared fetch ended: a later request fetches afresh


def test_concurrent_waiters_share_one_shielded_fetch(mock):
    server = mock(ok(), delay=0.2)
    async def both():
        hurried, patient = await asyncio.gather(portal.bottom_line(ARTIFACT, timeout=0.01), portal.bottom_line(ARTIFACT, timeout=5))
        return hurried, patient
    hurried, patient = run(both())
    # The hurried request's budget ran out without cancelling the fetch the other request was waiting for.
    assert (hurried.status, hurried.reason, patient.status, len(server.requests)) == ('unavailable', 'timeout', 'ok', 1)
    assert run(portal.bottom_line(ARTIFACT)).status == 'ok' and len(server.requests) == 1

    portal._CACHE.clear()
    server = mock(ok(), delay=0.2)
    async def abandoned():
        first = await portal.bottom_line(ARTIFACT, timeout=0.01)
        await asyncio.sleep(0.4)  # the shielded fetch finishes and caches its graph
        return first
    assert run(abandoned()).status == 'unavailable'
    assert run(portal.bottom_line(ARTIFACT)).status == 'ok' and len(server.requests) == 1


def test_stale_if_error_for_up_to_seven_days(mock, monkeypatch):
    clock = Clock(); monkeypatch.setattr(portal, 'time', clock)
    mock(ok())
    fresh = run(portal.bottom_line(ARTIFACT))
    def down(request): raise httpx.ConnectError('down', request=request)
    server = mock(down)
    clock.now += portal.FRESH_SECONDS - 1
    assert run(portal.bottom_line(ARTIFACT)) == fresh and not server.requests
    clock.now += 2
    stale = run(portal.bottom_line(ARTIFACT))
    assert stale.stale and stale.graph == fresh.graph and stale.sha256 == fresh.sha256 and len(server.requests) == 2
    clock.now += portal.STALE_SECONDS
    assert run(portal.bottom_line(ARTIFACT)).status == 'unavailable'


