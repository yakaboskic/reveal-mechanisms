#!/usr/bin/env python3
"""Generate config/pigean_collection.meta.yaml (and the traits table) for the PIGEAN claims-collection LAP pipeline.

Lists the PIGEAN run on S3 (needs the aws CLI and credentials): one trait instance per trait folder that holds
gs.out, gss.out and ggss.out. A trait key may hold shell characters (`Female_infertility_(all_causes)`), so the
instance name replaces them with `_` and the key stays in config/pigean_collection.traits.tsv, which every helper reads.
The CFDE libraries are the folders of the local mirror minus --exclude-library.

Then convert with meta-sanity:
  PYTHONPATH=/humgen/diabetes2/users/chase/packages/meta-sanity python3 -m meta_sanity.generate_meta \
      config/pigean_collection.meta.yaml config/pigean_collection.meta
"""

import argparse
import json
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from collection_workflow import (INSTANCE_RE, LIBRARY_RE, TRAIT_COLUMNS, WorkflowError, check,  # noqa: E402
                                 list_source_traits, write_tsv)

LAP_DIR = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SOURCE_URL = "s3://dig-pigean-paper-regression-2/out/falcon/staging/pigean/portal/"
SOURCE_LIBRARY = "mouse_msigdb"
CFDE_SNAPSHOT = "2026-11-24"
CFDE_ROOT = "/humgen/diabetes/users/chase/data/dig-s3/gene_sets/cfde"
# GaultonLab is in the bucket but is not a CFDE library (../lap leaves it out too). LINCS_L1000 (1.5M signatures, about
# 30 minutes and 24 GB per trait) is not mirrored into the snapshot.
DEFAULT_EXCLUDED_LIBRARIES = ["GaultonLab", "LINCS_L1000"]


def q(value):
    return json.dumps(str(value))


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    parser.add_argument("--project", default="pigean_portal__cfde_2026_11_24")
    parser.add_argument("--source-url", default=SOURCE_URL)
    parser.add_argument("--source-library", default=SOURCE_LIBRARY)
    parser.add_argument("--cfde-snapshot", default=CFDE_SNAPSHOT)
    parser.add_argument("--exclude-library", action="append", default=None,
                        help="Library of the mirror left out (repeatable; default: %s)" % ", ".join(DEFAULT_EXCLUDED_LIBRARIES))
    parser.add_argument("--only-traits", default=None, help="Comma-separated trait keys: a small test project")
    parser.add_argument("--output-file", default=os.path.join(LAP_DIR, "config", "pigean_collection.meta.yaml"))
    args = parser.parse_args(argv)

    cfde_dir = os.path.join(CFDE_ROOT, args.cfde_snapshot)
    check(os.path.isdir(cfde_dir), "No CFDE mirror at %s" % cfde_dir)
    excluded = set(DEFAULT_EXCLUDED_LIBRARIES if args.exclude_library is None else args.exclude_library)
    libraries = sorted(name for name in os.listdir(cfde_dir)
                       if os.path.isdir(os.path.join(cfde_dir, name, "genesets")) and name not in excluded)
    check(libraries and all(LIBRARY_RE.match(name) for name in libraries), "Unusable CFDE libraries: %s" % libraries)
    check(args.source_library not in libraries, "The source library %s is also a CFDE library" % args.source_library)

    traits, incomplete = list_source_traits(args.source_url, args.source_library)
    if args.only_traits:
        wanted = set(args.only_traits.split(","))
        missing = sorted(wanted - {t["trait"] for t in traits})
        check(not missing, "Not in the run: %s" % missing)
        traits = [t for t in traits if t["trait"] in wanted]
    check(traits, "No traits under %s" % args.source_url)
    names = [args.project] + [t["instance"] for t in traits]
    check(len(set(names)) == len(names) and all(INSTANCE_RE.match(n) for n in names), "Unsafe or colliding instance names")
    traits_file = args.output_file[:-len(".meta.yaml")] + ".traits.tsv"
    check(args.output_file.endswith(".meta.yaml"), "--output-file must end with .meta.yaml")
    write_tsv(traits_file, TRAIT_COLUMNS, traits)

    keys = [
        ("base_dir", LAP_DIR),
        ("unix_out_dir", "${base_dir}/out"),
        ("log_dir", "${base_dir}/log"),
        ("raw_dir", "${base_dir}/raw"),
        ("source_url", args.source_url),
        ("source_library", args.source_library),
        ("source_dir", "${raw_dir}/pigean_portal"),
        ("cfde_snapshot", args.cfde_snapshot),
        ("cfde_dir", cfde_dir),
        ("cfde_libraries", ",".join(libraries)),
        ("lap_home", "/humgen/diabetes/users/chase/lap"),
        ("web_out_dir", "http://internal.broadinstitute.org/~cyakabos/pigean-collection-lap"),
        ("default_umask", "002"),
    ]
    lines = [
        "# GENERATED by scripts/build_meta_yaml.py -- do not edit by hand; rerun the script instead.",
        "# 1 project, %d traits of %s (%d trait folders lack a file and are left out), %d CFDE libraries."
        % (len(traits), args.source_url, len(incomplete), len(libraries)),
        "config: %s" % q(os.path.join(LAP_DIR, "config", "pigean_collection.cfg")),
        "",
        "keys:",
    ]
    lines += ["  %s: %s" % (name, q(value)) for name, value in keys]
    lines += ["", "classes:",
              "  %s:" % q(args.project),
              "    class: project",
              "    parent: null",
              "    properties:",
              "      traits_in_file: %s" % q(os.path.abspath(traits_file)),
              "",
              "  # Traits: instance name = the trait key with shell characters replaced by _"]
    for trait in traits:
        lines += ["  %s:" % q(trait["instance"]),
                  "    class: trait",
                  "    parent: %s" % q(args.project)]
    with open(args.output_file, "w") as fh:
        fh.write("\n".join(lines) + "\n")
    print("Wrote %s and %s: %d traits (%d incomplete folders left out: %s), CFDE libraries %s (excluded: %s)"
          % (args.output_file, traits_file, len(traits), len(incomplete),
             ", ".join(t for t, _ in incomplete[:40]) or "none", ", ".join(libraries), ", ".join(sorted(excluded))))


if __name__ == "__main__":
    try:
        main()
    except WorkflowError as error:
        print("ERROR: %s" % error, file=sys.stderr)
        sys.exit(1)
